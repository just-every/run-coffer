import assert from 'node:assert/strict'
import {createHash,createHmac} from 'node:crypto'
import {privateEndpoint} from './cloudflare.mjs'

export async function proveDelivery({app,receiver,query,db,marker,afterDelivery}) {
 const history=()=>app.json('/api/coffer/webhooks')
 const state=()=>receiver.controlled('state')
 const tick=at=>app.controlled('tick',{at})
 const subscribe=(endpoint,events)=>app.command('webhook.subscribe',{name:'Coffer sandbox endpoint',endpoint,events,reviewed:'yes'})
 await app.json('/api/coffer/webhooks',undefined,{anonymous:true,status:401})
 assert.equal((await app.request('/_sandbox/ready',{anonymous:true})).status,404)
 console.log(JSON.stringify({stage:'anonymous-refusals-proven'}))
 const live=await subscribe(receiver.origin+'/events',['donor.created','gift.created','gift.reversed'])
 await receiver.controlled('key',{secret:live.secret},{status:204})
 assert.equal((await receiver.controlled('key',{secret:live.secret},{status:409})).error,'KEY_ALREADY_SET','A configured receiver refuses replacing its key')
 const redirect=await subscribe(receiver.origin+'/redirect',['gift.created'])
 const privateSub=await subscribe(privateEndpoint,['gift.created'])
 console.log(JSON.stringify({stage:'subscriptions-configured'}))
 const donor=await app.command('donor.create',{name:'Coffer sandbox donor',email:'synthetic-coffer-1@example.test',addressLine1:null})
 const gift=await app.command('gift.record',{donorId:donor.id,amount:'12.34',receivedOn:'2026-01-01',method:'check',goods:'none'})
 console.log(JSON.stringify({stage:'native-records-created'}))
 let log=await history()
 const original=log.deliveries.find(d=>d.subscription_id===live.id&&d.subject_id===gift.id)
 assert.ok(original,'Native gift produced the approved delivery')
 assert.ok(log.deliveries.some(d=>d.subscription_id===live.id&&d.subject_id===donor.id&&d.event_type==='donor.created'))
 assert.ok(!JSON.stringify(log).includes(live.secret),'Signing key is shown once')
 const initial=new Date(Math.max(Date.now(),...log.deliveries.map(d=>Date.parse(d.next_at)))+1000).toISOString()
 console.log(JSON.stringify({stage:'native-history-read',deliveries:log.deliveries.length}))
 await tick(initial)
 console.log(JSON.stringify({stage:'initial-tick-complete'}))
 log=await history()
 let target=log.deliveries.find(d=>d.id===original.id)
 assert.equal(target.status,'failed');assert.equal(target.attempts,1);assert.equal(target.last_status,503)
 assert.equal(log.attempts.find(a=>a.delivery_id===target.id).http_status,503)
 let received=await state()
 assert.equal(received.business[0].gifts,1,'Receiver committed its effect before returning 503')
 const canonical=JSON.stringify({id:target.event_id,type:'gift.created',occurredAt:target.occurred_at,data:{id:gift.id}})
 const digest=createHash('sha256').update(canonical).digest('hex')
 const first=received.receipts.find(r=>r.delivery_id===target.id)
 assert.ok(first,'A real HTTPS receiver verified the production HMAC')
 assert.equal(first.body_sha256,digest,'Exact signed bytes contain only the event and record identity')
 assert.ok(Math.abs(first.signature_timestamp-Date.now()/1000)<300)
 const redirected=log.deliveries.find(d=>d.subscription_id===redirect.id)
 assert.equal(redirected.status,'failed');assert.equal(redirected.last_status,307)
 assert.equal(received.hits.find(r=>r.name==='redirect').hits,1)
 assert.equal(received.hits.find(r=>r.name==='target').hits,0,'Production delivery never follows redirects')
 const privateDelivery=log.deliveries.find(d=>d.subscription_id===privateSub.id)
 assert.equal(privateDelivery.status,'failed','A lexically allowed hostname resolving privately cannot deliver')
 await app.command('webhook.pause',{subscriptionId:redirect.id,version:1})
 await app.command('webhook.pause',{subscriptionId:privateSub.id,version:1})
 const count=received.receipts.length
 await tick(new Date(Date.parse(target.next_at)-1).toISOString())
 assert.equal((await state()).receipts.length,count,'Backoff prevents an early network submission')
 await tick(target.next_at)
 log=await history();target=log.deliveries.find(d=>d.id===original.id)
 assert.equal(target.status,'delivered');assert.equal(target.attempts,2)
 assert.deepEqual(log.attempts.filter(a=>a.delivery_id===target.id).map(a=>[a.status,a.http_status]),[['failed',503],['delivered',204]])
 await app.command('webhook.replay',{deliveryId:target.id,reviewed:''},{status:400})
 const replay=await app.command('webhook.replay',{deliveryId:target.id,reviewed:'yes'})
 const pending=(await history()).deliveries.find(d=>d.id===replay.id)
 await tick(new Date(Math.max(Date.parse(pending.next_at),Date.parse(initial))+1000).toISOString())
 log=await history()
 const completed=log.deliveries.find(d=>d.id===replay.id)
 assert.equal(completed.status,'delivered');assert.equal(completed.replay_of,target.id);assert.equal(completed.event_id,target.event_id)
 assert.equal(log.deliveries.find(d=>d.id===target.id).attempts,2,'Reviewed replay preserves original history')
 received=await state()
 const giftReceipts=received.receipts.filter(r=>r.event_id===target.event_id)
 assert.equal(giftReceipts.length,3,'Initial send, retry and reviewed replay reached public HTTPS')
 assert.ok(giftReceipts.every(r=>r.body_sha256===digest),'Retries and replay preserve stable signed event bytes')
 assert.equal(received.seen.filter(r=>r.event_id===target.event_id).length,1)
 assert.equal(received.business[0].gifts,1,'Durable deduplication applies one business effect')
 const signed=timestamp=>`t=${timestamp},v1=${createHmac('sha256',live.secret).update(timestamp+'.'+canonical).digest('hex')}`
 const probe=async(signature,body)=>{
  const response=await receiver.request('/events',{method:'POST',raw:body,anonymous:true,headers:{'coffer-signature':signature,'coffer-event-id':target.event_id,'coffer-delivery-id':target.id}})
  assert.equal(response.status,401,'Receiver rejects invalid or stale exact signed bytes')
 }
 const now=Math.floor(Date.now()/1000)
 await probe(signed(now-301),canonical)
 await probe(signed(now+301),canonical)
 await probe(signed(now),canonical+' ')
 const after=await state()
 assert.equal(after.receipts.length,received.receipts.length);assert.equal(after.business[0].gifts,1)
 const tables=(await query(db,"SELECT name,sql FROM sqlite_master WHERE type='table' AND name LIKE 'cf_webhook_%'"))[0].results
 assert.ok(tables.length>=4)
 for(const table of tables){
  assert.ok(!/\b(?:body|response_body|payload)\b/i.test(table.sql),'Webhook schema has no retained response body')
  const rows=await query(db,'SELECT * FROM '+table.name)
  assert.ok(!JSON.stringify(rows).includes(marker),'Receiver response bytes are absent from durable application data')
 }
 assert.ok(!JSON.stringify(log).includes(marker),'Delivery log never exposes receiver response bytes')
 console.log(JSON.stringify({stage:'signed-delivery-proven',eventId:target.event_id,deliveryId:target.id,replayId:replay.id,receiverSubmissions:giftReceipts.length,durableGiftEffects:after.business[0].gifts,redirectTargetHits:after.hits.find(r=>r.name==='target').hits,responseBodyRetained:false}))
 if(afterDelivery)await afterDelivery({subscriptionId:live.id})
 const dns=await fetch('https://cloudflare-dns.com/dns-query?name='+new URL(privateEndpoint).hostname+'&type=A',{headers:{accept:'application/dns-json'},signal:AbortSignal.timeout(30000)})
 assert.equal(dns.status,200,'Public DNS resolver answered the private-host proof')
 const resolution=await dns.json()
 assert.ok(resolution.Answer?.some(a=>a.type===1&&a.data==='127.0.0.1'),'The accepted endpoint hostname resolves to a private address')
 const boundary=await app.controlled('private-network',{})
 console.log(JSON.stringify({stage:'private-network-observation',hostname:new URL(privateEndpoint).hostname,resolvesTo:'127.0.0.1',deliveryStatus:privateDelivery.last_status,...boundary}))
 assert.equal(boundary.prohibited,true,'Cloudflare must explicitly deny the private address; generic network failure does not prove the boundary')
 console.log(JSON.stringify({stage:'public-network-boundary-proven',strictlyPublic:true}))
}
