import assert from 'node:assert/strict'
import {generateKeyPairSync,sign} from 'node:crypto'
import {run,donor,reviewed,archive,restore,installation} from './harness.mjs'
const keys=generateKeyPairSync('ec',{namedCurve:'prime256v1'})
const publicKey=keys.publicKey.export({type:'spki',format:'der'}).toString('base64')
async function providerEvent(h,letter,event,eventId,extra={}) {
 const timestamp=String(Math.floor(Date.now()/1000)),raw=JSON.stringify([{event,sg_event_id:eventId,timestamp:Number(timestamp),coffer_letter_id:letter.id,coffer_attempt_id:letter.attempt_id,...extra}])
 return h.request('/api/coffer/mail/events',{method:'POST',as:'',raw,headers:{'x-twilio-email-event-webhook-timestamp':timestamp,'x-twilio-email-event-webhook-signature':sign('sha256',Buffer.from(timestamp+raw),keys.privateKey).toString('base64')}})
}
const gift=(h,donorId,amount,receivedOn='2025-08-10',extra={})=>h.command('gift.record',{donorId,amount,receivedOn,method:'check',goods:'none',...extra})
const consent=(h,donorId)=>h.command('consent.record',{donorIds:[donorId],channel:'email',status:'granted',method:'paper form',evidence:'Synthetic donor approved email',capturedOn:'2025-01-01'})

export function receiptDeliveryJourney() {
 const messages=[]
 return run(async h=>{
  await reviewed(h)
  const ana=await donor(h,'Ana Diaz'),ben=await donor(h,'Ben Cole'),cy=await donor(h,'Cy Park',{email:null}),dee=await donor(h,'Dee Morris')
  for(const d of [ana,ben,cy,dee])await consent(h,d.id)
  for(const d of [ana,ben,cy,dee])await gift(h,d.id,'250')
  const b=await h.command('ack.prepare')
  await h.command('ack.send',{batchId:b.id,version:1},{status:409})
  await h.command('ack.approve',{batchId:b.id,version:1})
  await h.command('consent.record',{donorIds:[ben.id],channel:'email',status:'withdrawn',method:'paper form',evidence:'Synthetic donor withdrew before dispatch',capturedOn:'2025-01-02'})
  const sent=await h.command('ack.send',{batchId:b.id,version:2})
  assert.equal(messages.length,3)
  assert.equal(sent.print,1)
  assert.deepEqual(messages.map(m=>m.personalizations[0].to[0].email).sort(),['ana.diaz@example.org','ben.cole@example.org','dee.morris@example.org'])
  assert.match(messages[0].content[0].value,/\$250\.00/)
  assert.match(messages[0].content[0].value,/No goods or services/)
  const detail=await h.get(`/api/coffer/letters/${b.id}`),letter=detail.letters.find(l=>l.donor_id===ana.id)
  assert.equal(letter.delivery_status,'submitted')
  await h.command('ack.checkDelivery',{batchId:b.id,version:sent.version})
  assert.equal((await h.get(`/api/coffer/letters/${b.id}`)).letters.find(l=>l.id===letter.id).delivery_status,'delivered')
  const invalid=await h.request('/api/coffer/mail/events',{method:'POST',as:'',body:[]});assert.equal(invalid.status,401)
  assert.equal((await providerEvent(h,letter,'delivered','delivery-1')).status,200)
  assert.equal((await providerEvent(h,letter,'delivered','delivery-1')).status,200)
  const delivered=await h.get(`/api/coffer/letters/${b.id}`)
  assert.equal(delivered.letters.find(l=>l.id===letter.id).delivery_status,'delivered')
  assert.equal(delivered.deliveryEvents.length,3)
  const openedLetter=detail.letters.find(l=>l.donor_id===ben.id)
  const occurred=Math.floor((Date.now()-86400000)/1000)
  const openExtra={timestamp:occurred,ip:'192.0.2.123',useragent:'private-test-user-agent'}
  assert.equal((await providerEvent(h,openedLetter,'open','open-1',openExtra)).status,200)
  assert.equal((await providerEvent(h,openedLetter,'open','open-1',openExtra)).status,200)
  assert.equal((await providerEvent(h,openedLetter,'open','open-2',openExtra)).status,200)
  assert.equal((await providerEvent(h,{...openedLetter,attempt_id:'wrong-attempt'},'open','spoof-open',openExtra)).status,200)
  assert.equal((await providerEvent(h,openedLetter,'open','old-open',{timestamp:1577836800})).status,200)
  let opened=(await h.get(`/api/coffer/donors/${ben.id}`)).engagement
  assert.equal(opened.opens.documents,1,'Repeated opens score one distinct document within the window')
  assert.equal(opened.opens.points,0,'Open weight defaults to zero')
  assert.equal(opened.opens.events.length,2,'Actual deduplicated events retain their provider provenance')
  assert.equal(opened.opens.provider,'SendGrid')
  const scorePolicy=await h.get('/api/coffer/engagement/settings')
  await h.command('engagement.settings',{version:scorePolicy.version,recency:0,frequency:0,amount:0,conversations:0,volunteering:0,opens:100})
  opened=(await h.get(`/api/coffer/donors/${ben.id}`)).engagement
  assert.equal(opened.opens.basePoints,5);assert.equal(opened.opens.points,20);assert.equal(opened.score,20)
  assert.equal((await h.get(`/api/coffer/letters/${b.id}`)).letters.find(l=>l.id===openedLetter.id).delivery_status,'delivered','Opening does not replace delivery outcome')
  const openDay=new Intl.DateTimeFormat('en-CA',{timeZone:'America/New_York'}).format(new Date(occurred*1000))
  const timeline=await (await h.request(`/app/donors/${ben.id}?timelineKind=receipt&timelineFrom=${openDay}&timelineTo=${openDay}`)).text()
  assert.equal((timeline.match(/SendGrid provider-reported open/g)||[]).length,2)
  const noOpens=await (await h.request(`/app/donors/${ben.id}?timelineKind=call&timelineFrom=${openDay}&timelineTo=${openDay}`)).text()
  assert.ok(!noOpens.includes('SendGrid provider-reported open'))
  const audit=await h.get(`/api/coffer/audit?record=${ana.id}&action=mail.delivered`)
  assert.ok(audit.rows.some(r=>r.subject_id===letter.id),'Provider delivery is retained in the organization audit log')
  assert.equal((await h.get(`/api/coffer/donors/${ana.id}`)).letters[0].delivery_status,'delivered')
  await h.command('ack.send',{batchId:b.id,version:sent.version})
  assert.equal(messages.length,3)
  assert.equal((await providerEvent(h,letter,'bounce','bounce-1')).status,200)
  assert.equal((await providerEvent(h,letter,'delivered','late-delivery')).status,200)
  const bounced=await h.get(`/api/coffer/letters/${b.id}`)
  assert.equal(bounced.letters.find(l=>l.id===letter.id).route,'print')
  assert.equal(bounced.letters.find(l=>l.id===letter.id).delivery_status,'bounced')
  assert.equal((await providerEvent(h,letter,'bounce','bounce-1')).status,200)
  const followup=(await h.get(`/api/coffer/donors/${ana.id}`)).receiptTasks
  assert.equal(followup.length,1,'A replay never duplicates the address task')
  assert.equal(followup[0].letter_id,letter.id)
  assert.equal(followup[0].completed_at,null)
  const donorPage=await (await h.request(`/app/donors/${ana.id}`)).text()
  assert.match(donorPage,/Fix email address/);assert.ok(donorPage.includes(`/print?letter=${letter.id}`))
  const invited=await h.request('/app/people/invite',{method:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},raw:new URLSearchParams({email:'receipt-followup@example.test',role:'member',displayName:'Receipt follow-up'}).toString()})
  assert.equal(invited.status,303)
  const invitation=messages.find(m=>m.personalizations[0].to[0].email==='receipt-followup@example.test')
  const link=invitation.content[0].value.match(/https?:[^\s<>]+\/auth\/confirm\?token=[^\s<>]+/)[0]
  const confirmed=await h.request('/auth/confirm',{method:'POST',as:'',body:{token:new URL(link).searchParams.get('token')}})
  assert.equal(confirmed.status,303)
  const member={cookie:confirmed.headers.getSetCookie().map(x=>x.split(';')[0]).join('; ')}
  const agent=await h.command('agent.create',{label:'Receipt reader'})
  await h.command('receiptTask.complete',{taskId:followup[0].id,version:1,resolution:'Checked with donor'},{as:'',headers:{authorization:'Bearer '+agent.token},status:403})
  await h.command('receiptTask.complete',{taskId:followup[0].id,version:1,resolution:'Checked with donor by phone; new address is still pending.'},{as:member.cookie})
  await h.command('receiptTask.complete',{taskId:followup[0].id,version:1,resolution:'stale completion'},{status:409})
  assert.ok((await h.get(`/api/coffer/donors/${ana.id}`)).receiptTasks[0].completed_at)
  assert.ok((await h.get('/api/coffer/audit?action=receiptTask.complete')).rows.some(r=>r.subject_id===followup[0].id))
  messages.splice(messages.indexOf(invitation),1)
  const print=await h.request(`/app/letters/${b.id}/print?pending=1`);assert.equal(print.status,200);assert.match(await print.text(),/Ana Diaz/)
  const single=await h.request(`/app/letters/${b.id}/print?letter=${letter.id}`);assert.match(await single.text(),/1 letter/)
  await h.command('ack.printed',{batchId:b.id,version:bounced.batch.version})
  const history=await h.request(`/app/donors/${ana.id}`);assert.match(await history.text(),/Bounced/)
  await gift(h,ana.id,'260','2025-10-01')
  const next=await h.command('ack.prepare');await h.command('ack.approve',{batchId:next.id,version:1})
  assert.equal((await h.command('ack.send',{batchId:next.id,version:2})).print,1)
  assert.equal(messages.length,3)
  if(process.env.COFFER_RECEIPT_BROWSER) {
   const {receiptDeliveryBrowser}=await import('./receipt-delivery-browser.mjs')
   await receiptDeliveryBrowser(h,{providerEvent,openedDonor:ben,directory:process.env.COFFER_RECEIPT_BROWSER})
   const snapshot=await archive(h),serialized=JSON.stringify(snapshot)
   assert.ok(!serialized.includes('192.0.2.123'));assert.ok(!serialized.includes('private-test-user-agent'))
   const fresh=await installation()
   try {
    await restore(fresh,snapshot)
    assert.deepEqual((await fresh.get(`/api/coffer/donors/${ben.id}`)).engagement,(await h.get(`/api/coffer/donors/${ben.id}`)).engagement)
    assert.deepEqual((await fresh.get(`/api/coffer/donors/${ana.id}`)).receiptTasks,(await h.get(`/api/coffer/donors/${ana.id}`)).receiptTasks)
   }finally{await fresh.close()}
   const into=await donor(h,'Ben Surviving',{email:'surviving.receipt@example.test'})
   const original=await h.get(`/api/coffer/donors/${ben.id}`),survivor=await h.get(`/api/coffer/donors/${into.id}`)
   const merged=await h.command('donor.merge',{sourceDonorId:ben.id,donorId:into.id,sourceVersion:original.donor.version,version:survivor.donor.version,reason:'duplicate_record'})
   assert.equal((await h.get(`/api/coffer/donors/${into.id}`)).engagement.opens.documents,1)
   await h.command('donor.unmerge',{mergeId:merged.mergeId,reason:'incorrect_match'})
   assert.equal((await h.get(`/api/coffer/donors/${ben.id}`)).engagement.opens.documents,1)
   await h.command('donor.erase',{donorId:ana.id,confirm:'ERASE'})
   const erased=JSON.stringify(await archive(h))
   assert.ok(!erased.includes('Checked with donor by phone; new address is still pending.'))
   assert.equal((await providerEvent(h,letter,'bounce','after-erasure')).status,200)
  }
 },{bindings:{MAIL_PROVIDER:'sendgrid',MAIL_EVENT_PUBLIC_KEY:publicKey},outbound:async r=>{
  const u=new URL(r.url);assert.equal(u.hostname,'api.sendgrid.com')
  if(u.pathname==='/v3/logs') {assert.equal(r.method,'POST');const query=(await r.json()).query;return Response.json({messages:messages.filter(m=>query.includes(m.personalizations[0].to[0].email)).map(m=>({sg_message_id:`provider-message-${messages.indexOf(m)+1}.recvd.0`,to_email:m.personalizations[0].to[0].email}))})}
  if(u.pathname.startsWith('/v3/logs/provider-message-')){const index=Number(u.pathname.match(/provider-message-(\d+)/)[1])-1;const m=messages[index];return Response.json({sg_message_id:`provider-message-${index+1}.recvd.0`,to_email:m.personalizations[0].to[0].email,events:[{event:'delivered',timestamp:Math.floor(Date.now()/1000),sg_event_id:`delivery-${index+1}`,custom_args:m.custom_args}]})}
  assert.equal(u.pathname,'/v3/mail/send');messages.push(await r.json());return new Response(null,{status:202,headers:{'x-message-id':`provider-message-${messages.length}`}})
 }})
}
