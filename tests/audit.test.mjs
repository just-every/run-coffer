import {test} from 'node:test'
import assert from 'node:assert/strict'
import {run,donor,reviewed} from './harness.mjs'

test('TEAM-003: owner filters changes by person, record and action and downloads the same audit as CSV',()=>run(async h=>{
 await reviewed(h)
 const member=await h.person('entry@example.test'),as={as:member.cookie}
 const a=await donor(h,'Avery Quinn',{},as),b=await donor(h,'Robin Cole')
 await h.command('gift.record',{donorId:a.id,amountCents:30000,receivedOn:'2026-10-01',method:'check',goods:'none'},as)
 const key=await h.command('agent.create',{label:'Receipt assistant'})
 const bearerBatch=await h.command('ack.prepare',{}, {as:'',headers:{authorization:`Bearer ${key.token}`}})
 const bearerRecord=await h.get('/api/coffer/letters/'+bearerBatch.id)
 assert.equal(bearerRecord.batch.prepared_by_name,'Receipt assistant for Morgan Lee')
 assert.equal(bearerRecord.batch.prepared_by_id,key.id);assert.equal(bearerRecord.batch.prepared_by_role,'agent')
 // The stored-key path has no bearer token and must resolve the same native
 // creator relation, separately from the person approving the standing grant.
 const creator=await h.person('audit.creator'+String.fromCharCode(64)+'example.test','admin')
 const storedKey=await h.command('agent.create',{label:'Stored receipt assistant'},{as:creator.cookie})
 const storedGift=await h.command('gift.record',{donorId:b.id,amountCents:50000,receivedOn:'2026-01-10',method:'check',goods:'none'})
 const grant=await h.command('agentGrant.save',{name:'Stored receipt approval',donorIds:[b.id],permissions:['ack.prepare','ack.send'],dailyLimit:1,standingApproval:true})
 await h.command('agentGrant.attach',{keyId:storedKey.id,grantId:grant.id})
 const policy=await h.get('/api/coffer/agent/receipts/settings')
 await h.api('/api/coffer/agent/receipts/settings',{version:policy.version,keyId:storedKey.id,maxStandardAmount:'1000',standingApproval:true})
 const result=await h.api('/api/coffer/agent/receipts/run',{})
 assert.equal(result.sent,1);assert.equal(result.batches.length,1)
 const storedBatch=await h.get('/api/coffer/letters/'+result.batches[0].id)
 const attribution='Stored receipt assistant for audit.creator'
 assert.equal(storedBatch.letters[0].gift_id,storedGift.id)
 assert.equal(storedBatch.batch.prepared_by_id,storedKey.id);assert.equal(storedBatch.batch.prepared_by_role,'agent')
 assert.equal(storedBatch.batch.prepared_by_name,attribution)
 assert.equal(storedBatch.approval.prepared_by_name,attribution);assert.equal(storedBatch.approval.approved_by_name,'Morgan Lee')
 assert.notEqual(storedBatch.approval.approved_by_id,creator.id)
 const storedEvents=storedBatch.events.filter(e=>e.actor_id===storedKey.id)
 assert.ok(storedEvents.length>0);assert.ok(storedEvents.every(e=>e.actor_name===attribution&&e.actor_role==='agent'))
 for(const e of storedEvents){
  const detail=JSON.parse(e.detail)
  assert.equal(detail.nativeKey.creatorId,creator.id);assert.equal(detail.nativeKey.creatorName,'audit.creator')
  assert.equal(detail.grantId,grant.id);assert.equal(detail.grantVersion,1)
 }
 const standing=storedEvents.find(e=>e.action==='ack.standingApproval'),standingDetail=JSON.parse(standing.detail)
 assert.equal(standingDetail.approvedById,storedBatch.approval.approved_by_id)
 assert.equal(standingDetail.approvedByName,'Morgan Lee');assert.equal(standingDetail.approvedByRole,'owner')
 assert.equal(standingDetail.approvalBasis,'standing-grant')
 const {mcpStoredBrowser}=await import('./mcp-browser.mjs')
 await mcpStoredBrowser(h,storedBatch.batch,storedKey,process.env.COFFER_MCP_BROWSER??'.cache/mcp',attribution)
 const {activity}=await h.get('/api/coffer/agent')
 assert.ok(activity.some(e=>e.subject_id===storedBatch.batch.id&&e.actor_id===storedKey.id&&e.actor_name===attribution))
 const priorCsv=await (await h.request('/api/coffer/audit.csv?person='+storedKey.id)).text()
 assert.ok(priorCsv.includes(attribution));assert.ok(priorCsv.includes(storedKey.id));assert.ok(!priorCsv.includes(storedKey.token))
 await h.command('agent.revoke',{id:storedKey.id})
 await h.api('/auth/operator/status',{operatorId:creator.id,status:'inactive'})
 await h.api('/api/coffer/agent/receipts/run',{},{status:401})
 const retained=await h.get('/api/coffer/letters/'+storedBatch.batch.id)
 assert.equal(retained.batch.prepared_by_name,attribution);assert.equal(retained.approval.approved_by_name,'Morgan Lee')
 assert.equal(await (await h.request('/api/coffer/audit.csv?person='+storedKey.id)).text(),priorCsv)
 const all=await h.get('/api/coffer/audit')
 assert.ok(all.rows.some(r=>r.action==='auth.signin'&&r.actor_id===member.id))
 assert.ok(all.rows.some(r=>r.actor_id===key.id&&r.action==='ack.prepare'))
 const query=new URLSearchParams({person:member.id,record:a.id,action:'gift.record',from:'2026-01-01',to:'2026-12-31'})
 const filtered=await h.get('/api/coffer/audit?'+query)
 assert.equal(filtered.total,1)
 assert.equal(filtered.rows[0].actor_id,member.id)
 assert.equal(filtered.rows[0].donor_id,a.id)
 const response=await h.request('/api/coffer/audit.csv?'+query),csv=await response.text()
 assert.equal(response.status,200)
 assert.match(csv,/gift.record/);assert.match(csv,/30000/)
 assert.ok(!csv.includes(b.id));assert.ok(!csv.includes(key.token));assert.ok(!csv.includes('token_hash'))
 const downloads=await h.get('/api/coffer/audit?action=export.download')
 assert.equal(downloads.rows[0].subject_id,'/api/coffer/audit.csv')
 assert.equal((await h.request('/app/audit')).status,200)
 await h.get('/api/coffer/audit',{...as,status:403})
 await h.get('/api/coffer/audit.csv',{as:'',headers:{authorization:`Bearer ${key.token}`},status:403})
 await h.get('/api/coffer/audit',{as:'',status:401})
}))

test('TEAM-003: the log pages without losing events and identity changes retain their actor',()=>run(async h=>{
 const member=await h.person('reader@example.test')
 for(let i=0;i<26;i++)await donor(h,`Community supporter ${i}`,{email:`supporter${i}@example.org`})
 const first=await h.get('/api/coffer/audit'),second=await h.get('/api/coffer/audit?page=1')
 assert.ok(first.more)
 assert.ok(second.rows.length)
 assert.ok(!second.rows.some(r=>first.rows.some(p=>p.id===r.id)))
 await h.api('/auth/operator/status',{operatorId:member.id,status:'inactive'})
 const result=await h.get('/api/coffer/audit?action=auth.operator.status')
 assert.equal(result.total,1)
 assert.equal(result.rows[0].actor_role,'owner')
}))
