import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { run, donor, reviewed, archive, restore } from './harness.mjs'
import { recognitionEdges, form } from './recognition-edge.mjs'

export async function campaignProgressJourney() {
 const edge = recognitionEdges()
 await run(async h => {
  await reviewed(h)
  const day = new Intl.DateTimeFormat('en-CA', {timeZone:'America/New_York'}).format(new Date())
  const publish = input => h.api('/api/coffer/giving/campaigns', {name:'Spring reading',slug:'spring-reading',description:'Books for every neighborhood.',fund:'Reading',goal:'60000',...input})
  await h.command('appealCode.define',{code:'SPRING',name:'Spring appeal'})
  await h.api('/api/coffer/giving/campaigns',{name:'Invalid',slug:'invalid',description:'Dates',fund:'Reading',goal:'1',startsOn:'2026-12-01',endsOn:'2026-01-01'},{status:400})
  const parent = await publish({startsOn:'2026-01-01',endsOn:'2026-12-31',appeals:['SPRING']})
  const child = await publish({name:'Neighborhood phase',slug:'neighborhood',parentId:parent.id,fund:'Neighborhood',goal:'10000'})
  await h.api('/api/coffer/giving/campaigns',{name:'Invalid parent',slug:'bad-parent',description:'Invalid',fund:'Reading',goal:'1',parentId:'missing'},{status:409})
  const member = await h.person('fundraiser@example.test')
  await h.api('/api/coffer/giving/campaigns',{name:'No',slug:'forbidden',description:'No',fund:'Reading',goal:'1'},{as:member.cookie,status:403})
  const ada = await donor(h,'Ada Existing'), ben = await donor(h,'Ben Pledger'), cara = await donor(h,'Cara Neighbor'), advisor = await donor(h,'Dana Advisor')
  const gift = (d,cents,campaignId=parent.id,fund='Reading',extra={})=>h.command('gift.record',{donorId:d.id,amountCents:cents,receivedOn:day,method:'check',goods:'none',fund,campaignId,...extra})
  await h.command('gift.record',{donorId:ada.id,amount:'10',receivedOn:'2024-01-01',method:'cash',goods:'none',fund:'Reading'})
  await gift(ada,10000,parent.id,'Reading',{appeal:'SPRING',channel:'mail'})
  const pledge = await h.command('pledge.create',{donorId:ben.id,amount:'300',pledgedOn:day,fund:'Reading',campaignId:parent.id,installments:[{dueOn:day,amount:'300'}]})
  await gift(ben,5000,parent.id,'Reading',{pledgeId:pledge.id,installmentId:pledge.installments[0].id})
  const neighborhood = await gift(cara,6000,child.id,'Neighborhood')
  await h.command('softCredit.record',{giftId:neighborhood.id,donorId:advisor.id,amount:'30'})
  const reversed = await gift(ada,2000)
  await h.command('gift.reverse',{giftId:reversed.id,reason:'Check returned',reversedOn:day})
  const checkout = await h.request('/give/spring-reading/checkout',{...form({name:'Eva Online',email:'eva.online@example.org',amount:'40',frequency:'once','cf-turnstile-response':'synthetic-coffer-security-token',requestId:randomUUID()}),as:''})
  assert.equal(checkout.status,303,await checkout.text())
  const session = new URL(checkout.headers.get('location')).pathname.split('/').at(-1)
  assert.equal((await h.request('/giving/thanks?session_id='+session,{as:''})).status,200)
  const read = id=>h.get('/api/coffer/giving/campaigns/'+id)
  await h.get('/api/coffer/giving/campaigns/'+parent.id,{as:'',status:401})
  await h.get('/api/coffer/giving/campaigns/missing',{status:404})
  const r = await read(parent.id), phase = await read(child.id)
  assert.deepEqual([r.campaign.goal_cents,r.campaign.starts_on,r.campaign.ends_on],[6000000,'2026-01-01','2026-12-31'])
  assert.equal(r.campaigns.find(c=>c.id===child.id).parent_id,parent.id)
  assert.deepEqual([...r.funds].sort(),['Neighborhood','Reading'])
  assert.deepEqual(r.appeals.map(a=>a.code),['SPRING'])
  assert.deepEqual(r.forms.map(f=>f.path).sort(),['/give/neighborhood','/give/spring-reading'])
  assert.deepEqual([r.raisedCents,r.pledgedOutstandingCents,r.softCreditCents,r.giftCount,r.donorCount,r.newDonors,r.recurringDonors,r.averageGiftCents],[25000,25000,3000,4,4,3,0,6250])
  assert.equal(r.entries.reduce((n,g)=>n+g.amount_cents,0),r.raisedCents)
  assert.deepEqual([phase.raisedCents,phase.softCreditCents,phase.donorCount],[6000,3000,1])
  assert.equal((await read(parent.id)).pledges[0].id,pledge.id)
  const html = await (await h.request('/app/giving/campaigns/'+parent.id,{as:member.cookie})).text()
  for(const expected of ['Spring reading','Neighborhood phase','$250.00','$30.00','$62.50','4 giving donors','3 first-time donors','SPRING','/give/spring-reading'])assert.ok(html.includes(expected),expected)
  if(process.env.COFFER_CAMPAIGN_BROWSER){const {campaignBrowser}=await import('./campaign-browser.mjs');await campaignBrowser(h,parent.id,process.env.COFFER_CAMPAIGN_BROWSER)}
  const saved = await archive(h)
  await run(async fresh=>{await restore(fresh,saved);const copied=await fresh.get('/api/coffer/giving/campaigns/'+parent.id);assert.deepEqual(copied,r)})
  await h.command('gift.reverse',{giftId:neighborhood.id,reason:'Returned',reversedOn:day})
  assert.deepEqual([(await read(parent.id)).raisedCents,(await read(parent.id)).softCreditCents],[19000,0])
  await h.command('donor.erase',{donorId:ben.id,confirm:'ERASE'})
  assert.equal((await read(parent.id)).raisedCents,19000,'erasure keeps received ledger cents')
 }, {bindings:{STRIPE_SECRET_KEY:'synthetic-coffer-6000'},outbound:edge.outbound})
}
