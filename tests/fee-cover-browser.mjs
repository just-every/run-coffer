import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {withBrowserWorker} from './browser-worker.mjs'

export async function feeCoverBrowser(h,{campaignId,directory='.cache/pay-004'}) {
 await mkdir(directory,{recursive:true})
 await withBrowserWorker(h,async(context,origin)=>{
  const page=await context.newPage();page.setDefaultTimeout(15000)
  // The redirect target is the paid network edge, never a simulated app page.
  await page.route('https://checkout.stripe.com/**',route=>route.fulfill({status:200,contentType:'text/plain',body:'Stripe checkout test boundary'}))
  for(const width of [1440,390]) {
   await page.setViewportSize({width,height:1000})
   await page.goto(origin+'/app/giving')
   const create=page.locator('form[action="/app/giving/campaigns"]')
   await create.getByLabel('Campaign name',{exact:true}).fill('After-school reading '+width)
   await create.getByLabel('Page address',{exact:true}).fill('after-school-reading-'+width)
   await create.getByLabel('Description',{exact:true}).fill('Books and tutoring for our neighborhood readers.')
   await create.getByLabel('Goal (USD)',{exact:true}).fill('5000')
   await create.getByLabel('Fund',{exact:true}).fill('Reading')
   await create.getByLabel('Offer optional donor fee cover',{exact:true}).check()
   await create.getByLabel('Estimated rate (basis points; 290 = 2.90%)',{exact:true}).fill('290')
   await create.getByLabel('Estimated fixed fee (cents; 30 = $0.30)',{exact:true}).fill('30')
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await create.screenshot({path:`${directory}/PAY-004-create-${width}.png`})
   await create.getByRole('button',{name:'Publish campaign',exact:true}).click()
   await page.getByRole('link',{name:'After-school reading '+width,exact:true}).click()
   await page.getByRole('heading',{name:'Donor fee cover',exact:true}).waitFor()
   assert.equal(await page.locator('form[action$="/fee-cover"]').getByLabel('Offer optional donor fee cover',{exact:true}).isChecked(),true)
   await page.screenshot({path:`${directory}/PAY-004-created-${width}.png`,fullPage:true})
   await page.goto(origin+'/app/giving/campaigns/'+campaignId)
   const config=page.locator('form[action$="/fee-cover"]')
   await config.getByLabel('Offer optional donor fee cover',{exact:true}).check()
   await config.getByLabel('Estimated rate (basis points; 290 = 2.90%)',{exact:true}).fill('290')
   await config.getByLabel('Estimated fixed fee (cents; 30 = $0.30)',{exact:true}).fill('30')
   await config.getByRole('button',{name:'Save fee cover',exact:true}).click();await page.waitForURL('**/app/giving/campaigns/'+campaignId)
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({path:`${directory}/PAY-004-config-${width}.png`,fullPage:true})
   await page.goto(origin+'/give/reading-fee-cover')
   await page.getByLabel('Gift amount (USD)',{exact:true}).fill('100.00')
   assert.equal(await page.locator('[name=feeCover]').isChecked(),false)
   await page.locator('[name=feeCover]').check()
   await page.getByLabel('Full name',{exact:true}).fill('Fee Cover Browser '+width)
   await page.getByLabel('Email address',{exact:true}).fill(`fee.browser.${width}@example.test`)
   await page.waitForFunction(()=>document.querySelector('[name=quotedAmountCents]')?.value==='10330')
   assert.match(await page.locator('#fee-cover-total').textContent(),/\$3\.30.*\$103\.30/)
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({path:`${directory}/PAY-004-total-${width}.png`,fullPage:true})
   await page.getByRole('button',{name:'Continue to secure checkout'}).click();await page.waitForURL('https://checkout.stripe.com/**')
   await page.goto(origin+'/app/payouts')
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({path:`${directory}/PAY-004-payouts-${width}.png`,fullPage:true})
   await page.getByRole('row').filter({hasText:'po_fee_cover'}).getByRole('link').click();await page.waitForURL('**/app/payouts/po_fee_cover')
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({path:`${directory}/PAY-004-payout-${width}.png`,fullPage:true})
   await page.getByRole('link',{name:'Fee report for this payout',exact:true}).click()
   await page.getByRole('heading',{name:'By giving form',exact:true}).waitFor()
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({path:`${directory}/PAY-004-fees-${width}.png`,fullPage:true})
   await page.getByLabel('Payout ID (optional)',{exact:true}).fill('')
   await page.getByRole('button',{name:'Show fee report',exact:true}).click()
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({path:`${directory}/PAY-004-all-fees-${width}.png`,fullPage:true})
   assert.deepEqual((await h.get('/api/coffer/payments/fees?payoutId=')).totals,(await h.get('/api/coffer/payments/fees')).totals)
  }
  await page.close()
 })
}
