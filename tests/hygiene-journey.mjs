import assert from 'node:assert/strict'
import {run,donor,reviewed,archive,restore} from './harness.mjs'
import {hygieneBrowser} from './hygiene-browser.mjs'

export async function hygieneJourney(){
 await run(async h=>{
  await reviewed(h)
  const first=await donor(h,'Marisol Alvarez',{phone:'202-555-0191'}),duplicate=await donor(h,'Marisol Alvarez',{email:'marisol.copy@example.org',phone:'2025550191'})
  const returned=await donor(h,'Rosa Morgan',{addressLine1:'8 River Road'}),family=await donor(h,'Helen Morgan',{addressLine1:'11 Cedar Road'}),addressed=await donor(h,'Avery Bennett',{addressLine1:'15 Ash Street'})
  const root='/api/coffer/agent/hygiene',state=()=>h.get(root),history=id=>h.get('/api/coffer/donors/'+id)
  const before=(await history(returned.id)).donor
  await h.api(root+'/evidence',{donorId:returned.id,source:'returned_mail',kind:'status',constituentStatus:'inactive',evidence:'Letter RMA-42 returned marked moved; owner proposes no current outreach.'})
  await h.api(root+'/evidence',{donorId:family.id,source:'family_note',kind:'status',constituentStatus:'deceased',deceasedOn:'2026-09-12',evidence:'Forwarded family notice FAM-21 states the date of death.'})
  await h.api(root+'/evidence',{donorId:addressed.id,source:'ncoa',kind:'address',addressLine1:'27 Oak Lane',city:'Chicago',region:'IL',postalCode:'60601',country:'United States',addressEffectiveOn:'2026-09-15',evidence:'Recorded NCOA result NCOA-23 supplies this complete forwarding address.'})
  await h.api(root+'/evidence',{donorId:family.id,source:'returned_mail',kind:'status',constituentStatus:'deceased',deceasedOn:'2026-09-12',evidence:'Return to sender'},{status:400})
  const prepared=await h.api(root+'/run',{})
  assert.equal((await history(returned.id)).donor.constituent_status,before.constituent_status)
  assert.equal((await history(returned.id)).donor.version,before.version)
  assert.equal((await history(addressed.id)).donor.address_line1,'15 Ash Street')
  assert.equal((await h.get('/api/coffer/duplicates')).count,1)
  assert.equal((await state()).proposals.length,prepared.proposals.length)
  assert.equal((await h.api(root+'/run',{})).proposals.length,prepared.proposals.length,'Repeat preparation does not duplicate proposals')
  const choose=(kind,id)=>prepared.proposals.find(p=>p.kind===kind&&p.donor_id===id)
  const status=choose('status',returned.id)
  assert.ok(status.evidence.includes('RMA-42'))
  await h.api(root+'/review',{id:status.id,decision:'accept'},{status:400})
  assert.equal((await history(returned.id)).donor.constituent_status,'active')
  if(process.env.COFFER_HYGIENE_BROWSER)await hygieneBrowser(h,{statusId:status.id},process.env.COFFER_HYGIENE_BROWSER)
  else await h.api(root+'/review',{id:status.id,decision:'accept',confirm:'ACCEPT'})
  assert.equal((await history(returned.id)).donor.constituent_status,'inactive')
  await h.api(root+'/review',{id:status.id,decision:'accept',confirm:'ACCEPT'},{status:409})
  const death=choose('status',family.id)
  await h.api(root+'/review',{id:death.id,decision:'accept',confirm:'ACCEPT'})
  assert.equal((await history(family.id)).donor.constituent_status,'deceased')
  const address=choose('address',addressed.id)
  await h.api(root+'/review',{id:address.id,decision:'accept',confirm:'ACCEPT'})
  assert.equal((await history(addressed.id)).donor.address_line1,'27 Oak Lane')
  assert.ok((await h.get('/api/coffer/donors/'+addressed.id+'/addresses')).history.some(a=>a.address_line1==='15 Ash Street'))
  const salutation=choose('salutation',first.id)
  await h.api(root+'/review',{id:salutation.id,decision:'accept',confirm:'ACCEPT'})
  assert.equal((await history(first.id)).donor.informal_salutation,'Marisol Alvarez')
  const rejected=choose('salutation',duplicate.id)
  await h.api(root+'/review',{id:rejected.id,decision:'reject'})
  assert.equal((await history(duplicate.id)).donor.informal_salutation,null)
  const oldMerge=prepared.proposals.find(p=>p.kind==='merge')
  await h.api(root+'/review',{id:oldMerge.id,decision:'accept',confirm:'ACCEPT'},{status:409})
  const current=await h.api(root+'/run',{}),merge=current.proposals.find(p=>p.kind==='merge'&&p.status==='pending')
  const combined=await h.api(root+'/review',{id:merge.id,decision:'accept',confirm:'ACCEPT'})
  assert.equal(combined.status,'accepted')
  assert.equal((await h.get('/api/coffer/duplicates')).count,0)
  const events=(await h.get('/api/coffer/audit')).rows
  for(const command of ['hygiene.accept','hygiene.reject','donor.merge','donor.profile','donor.update'])assert.ok(events.some(e=>e.action===command),command+' is audited')
  const member=await h.person('entry@example.test','member')
  await h.get(root,{as:member.cookie,status:403})
  await h.api(root+'/run',{},{as:member.cookie,status:403})
  await h.get(root,{as:'',status:401})
  const key=await h.command('agent.create',{label:'Preparation key'})
  await h.api(root+'/run',{},{as:'',headers:{authorization:'Bearer '+key.token},status:403})
  const saved=await archive(h)
  await run(async other=>{
   await restore(other,saved)
   const restored=await other.get(root)
   assert.equal(restored.proposals.find(p=>p.id===status.id).status,'accepted')
   assert.ok(restored.evidence.some(e=>e.evidence.includes('RMA-42')))
  },{entry:'tests/fixed-clock-worker.ts'})
  await h.command('donor.erase',{donorId:returned.id,confirm:'ERASE'})
  const afterErase=await state()
  assert.ok(!JSON.stringify(afterErase).includes('RMA-42'))
  assert.ok(!afterErase.proposals.some(p=>p.donor_id===returned.id))
 },{entry:'tests/fixed-clock-worker.ts'})
}
