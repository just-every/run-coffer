import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {run,donor,archive,restore} from './harness.mjs'
import {withBrowserWorker} from './browser-worker.mjs'

export async function portfoliosJourney(){
 await run(async h=>{
  const now='2026-10-15T16:00:00Z',headers={'x-test-now':now}
  const cmd=(name,input,options={})=>h.command(name,input,{...options,headers})
  const get=(path,options={})=>h.get(path,{...options,headers})
  const owner=(await get('/auth/session')).operator, riley=await h.person('riley@example.test')
  const ada=await donor(h,'Ada Rivera'),ben=await donor(h,'Ben Okafor'),chen=await donor(h,'Chen Foundation'),alias=await donor(h,'Ada Earlier Record')
  const leadership=await cmd('portfolio.save',{name:'Leadership circle',managerId:owner.id,untouchedDays:30})
  const foundations=await cmd('portfolio.save',{name:'Foundation partners',managerId:riley.id,untouchedDays:60})
  for(const [d,p] of [[ada,leadership],[ben,leadership],[chen,foundations]])await cmd('portfolio.assign',{donorId:d.id,portfolioId:p.id})
  await cmd('portfolio.save',{name:'Invalid',managerId:'missing',untouchedDays:30},{status:409})
  await cmd('portfolio.assign',{donorId:ada.id,portfolioId:foundations.id},{status:409})
  await cmd('portfolio.save',{name:'Denied',managerId:owner.id,untouchedDays:30},{as:'',status:401})
  const plan=(d,ownerId,askAmount)=>cmd('prospect.save',{donorId:d.id,ownerId,askAmount,stage:'cultivate',expectedCloseOn:'2026-12-01',nextStep:'Arrange a visit to the new reading room.'})
  await plan(ada,owner.id,'5000');await plan(ben,riley.id,'2000');await plan(chen,riley.id,'10000')
  // An opportunity owner differs from the donor's relationship manager.
  const fallback=await plan(alias,riley.id,'300')
  assert.ok(fallback.id)
  const contact=(d,on,as=h.owner)=>cmd('interaction.record',{donorId:d.id,kind:'meeting',occurredOn:on,who:'Board chair and donor',notes:'Discussed the library renewal and next proposal.',nextStep:'Send a proposal.'},{as})
  await contact(ada,'2026-09-01');await contact(ada,'2026-10-01');await contact(ada,'2026-10-15')
  await contact(ada,'2026-10-12',riley.cookie)
  await contact(ben,'2026-08-15')
  await contact(chen,'2026-10-10',riley.cookie)
  const gift=(d,amount,receivedOn)=>cmd('gift.record',{donorId:d.id,amount,receivedOn,method:'check',goods:'none',fund:'Library'})
  await gift(ada,'500','2026-10-01');const reversed=await gift(ada,'40','2026-10-02')
  await cmd('gift.reverse',{giftId:reversed.id,reason:'duplicate_entry'})
  await gift(ben,'200','2026-10-15');await gift(chen,'800','2026-10-05')
  await gift(ben,'100','2025-01-01')
  // An unanswered call is logged but is not a meaningful move or fresh contact.
  await cmd('pledge.create',{donorId:ben.id,amount:'90',pledgedOn:'2026-01-01',fund:'Library',installments:[{dueOn:'2026-09-01',amount:'90'}]})
  const source=(await get('/api/coffer/tasks')).sources.find(s=>s.donorId===ben.id)
  assert.ok(source)
  const call=await cmd('task.generate',{sourceKey:source.key,ownerId:owner.id,dueOn:'2026-10-15'})
  await cmd('task.complete',{taskId:call.id,version:call.version,outcome:'no_answer',notes:'No answer; try next week.'})
  const path='/api/coffer/portfolios?from=2026-10-01&through=2026-10-15'
  let report=await get(path),group=report.portfolios.find(p=>p.id===leadership.id)
  assert.deepEqual([group.size,group.moves,group.pipelineCents,group.raisedCents,group.untouched],[2,2,700000,70000,1])
  assert.equal(group.rows.find(r=>r.donor_id===ben.id).last_contact_on,'2026-08-15')
  assert.equal(group.rows.find(r=>r.donor_id===ada.id).moves,2)
  const rileyGroup=report.managers.find(m=>m.managerId===riley.id)
  assert.deepEqual([rileyGroup.size,rileyGroup.moves,rileyGroup.pipelineCents,rileyGroup.raisedCents],[2,1,1030000,80000])
  const filtered=await get(path+'&managerId='+owner.id)
  assert.equal(filtered.portfolios.length,1);assert.equal(filtered.size,2)
  await get('/api/coffer/portfolios?from=2026-10-16&through=2026-10-15',{status:400})
  await get('/api/coffer/portfolios?through=2027-01-01',{status:400})
  await get(path,{as:'',status:401})
  const page=await h.request('/app/portfolios',{headers});assert.equal(page.status,200)
  assert.match(await page.text(),/Ada Rivera/)
  if(process.env.COFFER_PORTFOLIOS_BROWSER){
   const directory=process.env.COFFER_PORTFOLIOS_BROWSER;await mkdir(directory,{recursive:true})
   await withBrowserWorker(h,async(context,origin)=>{
    await context.setExtraHTTPHeaders({cookie:h.owner,...headers})
    const page=await context.newPage()
    for(const width of [1440,390]){
     await page.setViewportSize({width,height:1000});await page.goto(origin+'/app/pipeline')
     await page.screenshot({path:`${directory}/MAJOR-002-pipeline-${width}.png`,fullPage:true})
     assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
     await page.getByRole('link',{name:'Portfolios and moves by manager'}).click()
     await page.getByLabel('From date',{exact:true}).fill('2026-10-01');await page.getByLabel('Through date',{exact:true}).fill('2026-10-15')
     await page.getByRole('button',{name:'Read portfolio report'}).click()
     assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
     await page.screenshot({path:`${directory}/MAJOR-002-portfolios-${width}.png`,fullPage:true})
     await page.getByLabel('Report manager').selectOption(owner.id)
     await page.getByRole('button',{name:'Read portfolio report'}).click()
     assert.equal(await page.getByRole('heading',{name:'Foundation partners',exact:true}).count(),0)
     await page.screenshot({path:`${directory}/MAJOR-002-filtered-${width}.png`,fullPage:true})
     // Create and edit with native forms, then assign a donor from the page.
     await page.getByLabel('Portfolio name',{exact:true}).last().fill(`Board outreach ${width}`)
     await page.getByLabel('Relationship manager').last().selectOption(owner.id)
     await page.getByLabel('Flag untouched after (days)',{exact:true}).last().fill('45')
     await page.getByRole('button',{name:'Create portfolio',exact:true}).click()
     assert.ok(await page.getByRole('heading',{name:`Board outreach ${width}`,exact:true}).isVisible())
     await page.screenshot({path:`${directory}/MAJOR-002-created-${width}.png`,fullPage:true})
     const row=()=>page.locator('li').filter({has:page.getByRole('link',{name:'Ada Rivera',exact:true})})
     await row().getByText('Change portfolio',{exact:true}).click()
     await row().getByLabel('Move to portfolio').selectOption({label:`Board outreach ${width}`})
     await row().getByRole('button',{name:'Assign portfolio',exact:true}).click()
     const board=page.locator('section').filter({has:page.getByRole('heading',{name:`Board outreach ${width}`,exact:true})})
     assert.ok(await board.getByRole('link',{name:'Ada Rivera',exact:true}).isVisible())
     await page.screenshot({path:`${directory}/MAJOR-002-assigned-${width}.png`,fullPage:true})
     await row().getByText('Change portfolio',{exact:true}).click()
     await row().getByLabel('Move to portfolio').selectOption(leadership.id)
     await row().getByRole('button',{name:'Assign portfolio',exact:true}).click()

    }
   })
  }
  // A manager/threshold edit changes the report and stale edits refuse.
  await cmd('portfolio.save',{portfolioId:leadership.id,version:leadership.version,name:'Leadership circle',managerId:owner.id,untouchedDays:90})
  await cmd('portfolio.save',{portfolioId:leadership.id,version:leadership.version,name:'Stale',managerId:owner.id,untouchedDays:90},{status:409})
  assert.equal((await get(path)).portfolios.find(p=>p.id===leadership.id).untouched,0)
  const saved=await archive(h)
  await run(async fresh=>{await restore(fresh,saved);const copied=await fresh.get(path);assert.equal(copied.size,report.size);assert.equal(copied.raisedCents,report.raisedCents)})
  const comparison=await get(`/api/coffer/duplicates/compare?source=${alias.id}&target=${ada.id}`)
  const merged=await cmd('donor.merge',{sourceDonorId:alias.id,donorId:ada.id,sourceVersion:comparison.source.version,version:comparison.target.version,reason:'duplicate_record'})
  report=await get(path);assert.equal(report.size,3)
  assert.equal(report.portfolios.find(p=>p.id===leadership.id).pipelineCents,730000)
  await cmd('donor.unmerge',{mergeId:merged.mergeId,reason:'incorrect_match'})
  assert.equal((await get(path)).size,4)
  await cmd('donor.erase',{donorId:ada.id,confirm:'ERASE'})
  report=await get(path);assert.equal(report.size,3)
  assert.ok(!JSON.stringify(report).includes('Ada Rivera'))
 },{entry:'tests/advancing-clock-worker.ts'})
}
