import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { run, donor, archive, restore, settings } from './harness.mjs'
import { withBrowserWorker } from './browser-worker.mjs'

export async function taxReportsJourney() {
 await run(async h => {
  const headers = { 'x-test-now':'2026-10-15T00:30:00Z' }, options = { headers }
  const get = (path, extra = {}) => h.get(path, { ...extra, headers })
  const command = (name, input, extra = {}) => h.command(name, input, { ...extra, headers })
  const currentSettings = await get('/api/coffer/settings')
  await command('settings.update', { ...settings, version:currentSettings.version, fiscalYearStart:'07-01' })
  const ada = await donor(h,'Ada Rivera'), ben = await donor(h,'Ben Wells'), exact = await donor(h,'Cara Moss'), above = await donor(h,'Drew Park')
  const below = await donor(h,'Ellen Noor'), property = await donor(h,'Farah Chen'), erased = await donor(h,'Graham Voss'), credited = await donor(h,'Helen Li')
  const gift = (d, amount, receivedOn, extra = {}) => command('gift.record', { donorId:d.id, amount, receivedOn, method:'check', goods:'none', ...(extra.allocations ? {} : { fund:'Library' }), ...extra })
  for (const [index,year] of [2021,2022,2023,2024].entries()) {
   await gift(ada,String((index+1)*100),`${year}-06-01`)
   await gift(ben,'50',`${year}-06-01`)
  }
  await gift(ada,'3000','2025-01-01')
  const split = await gift(ada,'2000','2025-12-31',{ allocations:[{ fund:'Books',amount:'750' },{ fund:'Meals',amount:'1250' }] })
  await command('softCredit.record',{ giftId:split.id, donorId:credited.id, amount:'2000' })
  await gift(ben,'6000','2025-06-01')
  const returned = await gift(ben,'1000','2025-07-01')
  await command('gift.reverse',{ giftId:returned.id, reversedOn:'2025-07-02', reason:'Returned check' })
  await gift(exact,'10000','2025-06-01'); await gift(above,'10000.01','2025-06-01'); await gift(below,'4999.99','2025-06-01')
  await gift(erased,'700','2025-06-01')
  const oldProperty = await command('inKind.save',{ donorId:property.id, description:'Archive shelf', quantity:'1', statedValue:'400', receivedOn:'2023-06-01', goods:'none' })
  let currentProperty = await command('inKind.save',{ donorId:property.id, description:'Reading tables', quantity:'2', statedValue:'5500', receivedOn:'2025-07-01', goods:'none' })
  currentProperty = await command('inKind.save',{ donorId:property.id, inKindId:currentProperty.id, version:currentProperty.version, description:'Reading tables', quantity:'2', statedValue:'6000',correctionReason:'Donor corrected the stated value after inventory', receivedOn:'2025-07-01', goods:'none' })
  await command('inKind.dispose',{donorId:property.id,inKindId:currentProperty.id,version:currentProperty.version,disposedOn:'2025-12-01',disposalMethod:'sold',disposalEvidence:'Tables sold after replacement.'})
  await command('inKind.save',{donorId:erased.id,description:'Donated shelves from Graham',quantity:'1',statedValue:'100',receivedOn:'2025-06-01',goods:'none'})
  await command('donor.erase',{ donorId:erased.id, confirm:'ERASE' })
  const path = '/api/coffer/reports/tax?year=2025'
  await get(path,{ as:'', status:401 })
  await get('/api/coffer/reports/tax?year=2025junk',{ status:400 })
  let report = await get(path)
  assert.equal(report.scheduleA.monetaryCents,3790000)
  assert.equal(report.scheduleB.contributionTotalCents,3670000)
  assert.deepEqual(report.scheduleA.totals.map(y=>y.monetaryCents),[15000,25000,35000,45000,3670000])
  assert.equal(report.scheduleA.noncashStatedCents,650000)
  const adaHistory = report.scheduleA.donors.find(d=>d.donorId===ada.id)
  assert.deepEqual(adaHistory.years.map(y=>y.monetaryCents),[10000,20000,30000,40000,500000])
  assert.equal(adaHistory.monetaryCents,600000)
  assert.equal(report.scheduleA.donors.find(d=>d.donorId===ben.id).years[4].monetaryCents,600000)
  assert.ok(!report.scheduleA.donors.some(d=>d.donorId===credited.id))
  assert.equal(report.scheduleA.donors.find(d=>d.donorId===null).monetaryCents,70000)
  assert.ok(!JSON.stringify(report).includes('Graham'))
  const generalIds = [ada,ben,exact,above,property].map(d=>d.id).sort()
  assert.deepEqual(report.scheduleB.rows.map(d=>d.donorId).sort(),generalIds)
  assert.equal(report.scheduleB.rows.reduce((n,d)=>n+d.monetaryCents,0)+report.scheduleB.belowThresholdMonetaryCents+report.scheduleB.unidentified.monetaryCents,report.scheduleB.contributionTotalCents)
  assert.equal(report.scheduleM.statedValueCents,610000)
  assert.equal(report.scheduleM.giftCount,2)
  assert.equal(report.scheduleM.rows.find(g=>g.id===currentProperty.id).disposedOn,'2025-12-01')
  assert.equal(report.scheduleM.rows.find(g=>g.donorId===null).statedValueCents,10000)
  assert.equal(report.scheduleB.unidentified.noncashStatedCents,10000)
  assert.ok(!report.scheduleM.rows.some(g=>g.id===oldProperty.id))
  // The setting uses existing settings-manager authority; reads retain donor access.
  const member = await h.person('tax-member@example.test')
  assert.equal((await get(path,{ as:member.cookie })).scheduleA.monetaryCents,3790000)
  const agent=await command('agent.create',{label:'Tax working papers reader'}),agentOptions={as:'',headers:{...headers,authorization:'Bearer '+agent.token}}
  assert.equal((await h.get(path,agentOptions)).scheduleA.monetaryCents,3790000)
  const save = { version:report.configuration.version, rule:'public_support', eligibilityConfirmed:true, periodStart:report.start, periodThrough:report.through, totalContributions:'500000' }
  await command('taxReports.settings',save,{ as:'', status:401 })
  await command('taxReports.settings',save,{ as:member.cookie, status:403 })
  await h.command('taxReports.settings',save,{...agentOptions,status:403})
  await command('taxReports.settings',{ ...save, eligibilityConfirmed:false },{ status:400 })
  await command('taxReports.settings',save)
  await command('taxReports.settings',save,{ status:409 })
  report = await get(path)
  assert.deepEqual(report.scheduleB.rows.map(d=>d.donorId),[above.id],'Exactly 2% is excluded; one cent above is included')
  assert.equal(report.scheduleB.denominatorCents,50000000)
  assert.equal(report.scheduleA.monetaryCents,3790000)
  await command('taxReports.settings',{ ...save, version:report.configuration.version, totalContributions:'100000' })
  report = await get(path)
  assert.deepEqual(report.scheduleB.rows.map(d=>d.donorId).sort(),generalIds,'The $5,000 minimum remains inclusive when it is above 2%')
  const fiscal = await get(path+'&basis=fiscal')
  assert.equal(fiscal.start,'2025-07-01'); assert.equal(fiscal.through,'2026-06-30')
  assert.equal(fiscal.scheduleB.needsContributionTotal,true,'A different reporting period requires its own return denominator')
  assert.equal(fiscal.scheduleA.donors.find(d=>d.donorId===ada.id).years[4].monetaryCents,200000)
  const today = await get('/api/coffer/reports/tax?basis=fiscal')
  assert.equal(today.through,'2026-10-14','Current period ends on today in the organization timezone')
  assert.equal(today.year,2026)
  const audit = await get('/api/coffer/audit?action=taxReports.settings')
  assert.ok(audit.rows.some(e=>e.action==='taxReports.settings'))
  const saved = await archive(h)
  await run(async fresh => {
   await restore(fresh,saved)
   const copied = await fresh.get(path,options)
   assert.deepEqual(copied.configuration,report.configuration)
   assert.deepEqual(copied.scheduleA,report.scheduleA)
   assert.deepEqual(copied.scheduleB,report.scheduleB)
   assert.deepEqual(copied.scheduleM,report.scheduleM)
  })
  const response = await h.request('/app/reports/tax?year=2025',options)
  assert.equal(response.status,200)
  assert.match(response.headers.get('content-type'),/text\/html/)
  if (process.env.COFFER_TAX_BROWSER) await browserProof(h,headers,process.env.COFFER_TAX_BROWSER)
 },{entry:'tests/advancing-clock-worker.ts'})
}

async function browserProof(h,headers,directory) {
 await mkdir(directory,{ recursive:true })
 await withBrowserWorker(h,async (context,origin) => {
  await context.setExtraHTTPHeaders({ cookie:h.owner,...headers })
  const page = await context.newPage()
  for (const width of [1440,390]) {
   await page.setViewportSize({ width,height:1000 })
   await page.goto(origin+'/app/retention')
   const entry=page.getByRole('link',{name:'Form 990 support',exact:true});await entry.scrollIntoViewIfNeeded();await page.screenshot({path:`${directory}/REPORT-007-entry-link-${width}.png`});await entry.click()
   await page.getByLabel('Start year',{ exact:true }).fill('2025')
   await page.getByRole('button',{ name:'View report',exact:true }).click()
   await page.locator('select[name="rule"]').selectOption('general')
   await page.getByRole('button',{ name:'Save reporting rule',exact:true }).click()
   assert.equal(new URL(page.url()).searchParams.get('year'),'2025')
   assert.equal(await page.locator('select[name=rule]').inputValue(),'general')
   await page.getByRole('link',{ name:'Ada Rivera',exact:true }).first().waitFor()
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await page.screenshot({ path:`${directory}/REPORT-007-tax-${width}.png` })
   for(const [key,title] of [['contributors','Schedule B · contributors'],['five-years','Schedule A · five years of giving'],['noncash','Schedule M · noncash contributions']])await page.locator('section').filter({has:page.getByRole('heading',{name:title,exact:true})}).screenshot({path:`${directory}/REPORT-007-${key}-${width}.png`})
   await page.locator('select[name="rule"]').selectOption('public_support')
   await page.locator('input[name=totalContributions]').fill('500000')
   await page.locator('input[name=eligibilityConfirmed]').check()
   await page.getByRole('button',{ name:'Save reporting rule',exact:true }).click()
   assert.equal(new URL(page.url()).searchParams.get('year'),'2025')
   assert.equal(await page.locator('select[name=rule]').inputValue(),'public_support')
   await page.locator('section').filter({has:page.getByRole('heading',{name:'Schedule B · contributors',exact:true})}).screenshot({ path:`${directory}/REPORT-007-special-${width}.png` })
  }
 })
}
