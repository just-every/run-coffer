const crmInput=(giftId,amount)=>({source:'lgl',files:[
 ['constituents.csv','LGL Constituent ID,Name,Email Address,Note\n801,Harper Ellis,harper.crm@example.org,Private outreach preference from the legacy CRM.\n'],
 ['gifts.csv',`LGL Gift ID,LGL Constituent ID,Gift Type,Gift Date,Amount,Fund,Payment Type,Non-Deductible Amount\n${giftId},801,Gift,2025-06-01,${amount},Library,Check,0.00\n`],
].map(([name,body])=>({name,base64:Buffer.from(body).toString('base64')}))})
async function moveIn(h,input){
 const preview=await h.api('/api/coffer/move-in/preview',input)
 assert.equal(preview.canApply,true,JSON.stringify(preview.diagnostics))
 let job=await h.api('/api/coffer/move-in/apply',{id:preview.id,fingerprint:preview.fingerprint})
 while(job.state==='applying')job=await h.api('/api/coffer/move-in/continue',{id:preview.id})
 return job
}

